#!/usr/bin/env python3
"""Generate README.md for the cached-dispatch Xid31 reproduction from runs.tsv + cuda_gdb.tsv (never hand-copy).

runs.tsv     one row per Megatron run: arm, tag, start_utc, secs, last_step, xid_before, xid_after
             (the rotation driver's summary, ~/xid31_ab_summary.tsv, copied here at the end)
cuda_gdb.tsv one row per GPU coredump analysed: tag, node, gpu, step, block, thread, fwd_warp,
             channel, insn, dst
"""
import csv
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ARMS = {
    'base': 'DeepEP 874779c (unpatched)',
    'pr5': '874779c + PR #5 (merged, conflict resolved)',
    'min': '874779c + min patch (cached data channels above QP 0)',
    'probe': '874779c + probe patch (EP_PROBE + slot/dst guard)',
}


def xid_delta(before, after):
    b = [int(x) for x in before.split(',') if x]
    a = [int(x) for x in after.split(',') if x]
    if len(a) != len(b) or not a:
        return None
    return sum(1 for x, y in zip(b, a) if y > x)


def secs(v):
    v = v.lstrip('~')
    return float(v) if v.replace('.', '').isdigit() else float('nan')


def main():
    runs = sorted(csv.DictReader(open(os.path.join(HERE, 'runs.tsv')), delimiter='\t'), key=lambda r: r['start_utc'])
    gdb = list(csv.DictReader(open(os.path.join(HERE, 'cuda_gdb.tsv')), delimiter='\t'))
    npath = os.path.join(HERE, 'notes.tsv')
    notes = {r['tag']: r['note'] for r in csv.DictReader(open(npath), delimiter='\t')} if os.path.exists(npath) else {}
    out = []
    w = out.append
    w('# Xid 31 in DeepEP v2 cached hybrid dispatch -- reproduced on 4 x p6-b200\n')
    w('Generated by `make_readme.py` from `runs.tsv` and `cuda_gdb.tsv`; do not edit by hand.\n')
    w('Setup: 4 x p6-b200.48xlarge (32 GPUs = one EP32 group, 4 NVLink domains), EFA 1.50.0, NCCL 2.31.2, '
      'GIN type 5, Megatron-LM dev 1edcc0c + TE 2.20.2, `deepepv2` flex backend, '
      '`--overlap-moe-expert-parallel-comm`, 28 DeepEP SMs, 11 GIN contexts, 8192 tokens/rank, MBS 1, GA 2, '
      'MTP 1, 24 layers, mock data, seed 1234. The MoE shape measured here is private: the published '
      '`repro_xid31/shape.env` holds DeepSeek-R1-like placeholders, not that shape, and the per-node logs '
      '(which print the full argument list) are kept out of the repo. Arms rotate on the same 4 nodes.\n')
    w('## Runs\n')
    w('| arm | tree | run | start (UTC) | duration (min) | last logged step | failed (Xid on a new node) | note |')
    w('|---|---|---|---|---:|---:|---|---|')
    tot = {}
    for r in runs:
        d = xid_delta(r['xid_before'], r['xid_after'])
        failed = 'yes' if d else ('no' if d == 0 else '?')
        if r['arm'] == 'probe':
            failed = 'no Xid; Inf grad norm'
        s = secs(r['secs'])
        w('| %s | %s | %s | %s | %s | %s | %s | %s |' % (r['arm'], ARMS.get(r['arm'], ''), r['tag'],
          r['start_utc'], '-' if math.isnan(s) else '%.1f' % (s / 60), r['last_step'], failed,
          notes.get(r['tag'], '')))
        t = tot.setdefault(r['arm'], [0, 0.0, 0])
        t[0] += 1
        t[1] += 0 if math.isnan(s) else s
        t[2] += 1 if (d and r['arm'] != 'probe') else 0
    w('\n| arm | runs | total minutes | Xid failures | failures per hour |')
    w('|---|---:|---:|---:|---:|')
    for arm, (n, s, f) in tot.items():
        w('| %s | %d | %.1f | %d | %.1f |' % (arm, n, s / 60, f, f / (s / 3600) if s else 0))
    w('\n## GPU coredumps (cuda-gdb)\n')
    w('| run | node | GPU | faulting step | block | thread | forward warp | channel | faulting insn | TMA dst |')
    w('|---|---|---|---:|---|---:|---:|---:|---|---|')
    for g in gdb:
        w('| %s | %s | %s | %s | %s | %s | %s | %s | `%s` | `%s` |' % (
          g['tag'], g['node'], g['gpu'], g['step'], g['block'], g['thread'], g['fwd_warp'],
          g['channel'], g['insn'], g['dst']))
    w('\nEvery fault is in `hybrid_unordered_dispatch_impl<kDoCPUSync=0, kReuseSlotIndices=1, ..., '
      'kNumNotifyWarps=0, ...>` (cached dispatch = combine backward), block 0, a forward warp of channel 0, 1 '
      'or 2 -- exactly the three channels whose signal ids collide with the rail barrier -- at the same `UBLKCP.G.S` (TMA bulk store smem->global) with a destination ~0x185/0x186_xxxxxxxx '
      'that is outside every live allocation (valid device pointers are 0x7c..).\n')
    w('## Mechanism\n')
    w('In cached mode `num_notify_warps = 0` (dispatch.hpp:251), so `kQPStartIdx = 0` (qp_mapping.cuh:78) and '
      'the data channels are spread over QP 0..10. With 28 SMs > 11 QPs, channels 0..17 land on QP 0 with '
      'per-part signal ids 0..17 (kNumParts = 1). The rail barrier (`gin_barrier_wo_local_sync`, run only by '
      'block 0) uses QP 0 signal ids 0..num_rdma_ranks-2 = 0..2. Channels 0..2 therefore share a GIN '
      'counter with the barrier: a fast peer\'s data increment satisfies the barrier slot, the real barrier '
      'increment then counts as data (landed = expected + 1), and the forward warp TMA-forwards a token whose '
      'payload has not landed (SRD may deliver the in-band header first). A garbage destination rank/slot '
      'gives the wild write (Xid 13/31); a valid-but-wrong one silently corrupts gradients (Inf/NaN).\n')
    w('The probe arm observed it directly: `data_overcount` / `foreign_increment` fire only on channels 1 '
      'and 2, always exactly +1, and `stale_payload` caught corrupted payloads (two would have been wild '
      'writes, one a silent wrong forward); that run then aborted with `found Inf in local grad norm for '
      'bucket #0 in backward pass before data-parallel communication collective` on all 32 ranks of the '
      'EP group -- the same bug can surface as an Inf/NaN gradient instead of an Xid.\n')
    open(os.path.join(HERE, 'README.md'), 'w').write('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
